/**
 * Layout constants.
 *
 * Screen gutters were 16px, which put text and tap targets uncomfortably close
 * to the edge - especially on phones with curved glass, where the last few
 * pixels are physically hard to reach and visually distorted. 20px is the
 * comfortable minimum for a phone held one-handed.
 */
export const GUTTER = 20;

/** Clears the tab bar so the last row of a list is never trapped underneath. */
export const LIST_BOTTOM_PAD = 28;
